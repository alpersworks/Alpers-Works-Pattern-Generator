import type { PatternResult, PatternState, Point2D, PolygonRing } from '../engine/types';

function fmt(n: number): string {
  return Number(n.toFixed(3)).toString();
}

function ringToPathD(ring: PolygonRing): string {
  if (ring.length < 3) return '';
  let d = `M${fmt(ring[0].x)} ${fmt(ring[0].y)}`;
  for (let i = 1; i < ring.length; i++) {
    d += `L${fmt(ring[i].x)} ${fmt(ring[i].y)}`;
  }
  return d + 'Z';
}

function transformRing(
  ring: PolygonRing,
  x: number,
  y: number,
  angle: number,
  scale: number
): PolygonRing {
  const cos = Math.cos(angle);
  const sin = Math.sin(angle);
  return ring.map((p: Point2D) => {
    const sx = p.x * scale;
    const sy = p.y * scale;
    return {
      x: x + sx * cos - sy * sin,
      y: y + sx * sin + sy * cos,
    };
  });
}

export function resolveVisualColors(state: PatternState): {
  panelFill: string;
  holeFill: string;
  holeStroke: string;
  outlineStroke: string;
} {
  if (state.studioMode === 'cad_wireframe') {
    return {
      panelFill: '#FFFFFF',
      holeFill: 'none',
      holeStroke: '#D93025',
      outlineStroke: '#1A73E8',
    };
  }
  if (state.studioMode === 'acoustic_dark') {
    return {
      panelFill: state.panelColor === '#FFFFFF' ? '#16181C' : state.panelColor,
      holeFill: state.holeColor === '#1A1A1A' ? '#E4E4E7' : state.holeColor,
      holeStroke: state.holeColor === '#1A1A1A' ? '#E4E4E7' : state.holeColor,
      outlineStroke: '#3F3F46',
    };
  }
  if (state.studioMode === 'brushed_metal') {
    return {
      panelFill: '#C8CDD4',
      holeFill: '#101113',
      holeStroke: '#101113',
      outlineStroke: '#71717A',
    };
  }
  return {
    panelFill: state.panelColor,
    holeFill: state.holeColor,
    holeStroke: state.holeColor,
    outlineStroke: '#D4D4D8',
  };
}

/**
 * Generates a 1:1 millimeter Graphic / Illustrator / Figma SVG.
 */
export function buildGraphicSvg(state: PatternState, result: PatternResult): string {
  const { panelW, panelH, transparentBg, renderStyle, strokeWidth } = state;
  const colors = resolveVisualColors(state);
  const panelD = ringToPathD(result.panelOutline);

  const holePaths: string[] = [];
  for (const inst of result.instances) {
    const rings = inst.clippedRings
      ? inst.clippedRings
      : result.baseRings.map((r) => transformRing(r, inst.x, inst.y, inst.angle, inst.scale));
    const d = rings.map(ringToPathD).filter(Boolean).join(' ');
    if (d) holePaths.push(d);
  }

  const combinedHolesD = holePaths.join(' ');
  const fillAttr =
    state.studioMode === 'cad_wireframe' || renderStyle === 'stroke'
      ? 'none'
      : colors.holeFill;
  const strokeAttr =
    state.studioMode === 'cad_wireframe'
      ? colors.holeStroke
      : renderStyle === 'stroke' || renderStyle === 'fill_stroke'
      ? colors.holeStroke
      : 'none';
  const strokeW = state.studioMode === 'cad_wireframe' ? 0.4 : strokeWidth;

  const bgElement = transparentBg
    ? ''
    : `  <path id="panel-background" d="${panelD}" fill="${colors.panelFill}" />`;

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(panelW)}mm" height="${fmt(panelH)}mm" viewBox="0 0 ${fmt(panelW)} ${fmt(panelH)}">`,
    `  <!-- Generated by Alper's Works Pattern Generator (1:1 mm) -->`,
    bgElement,
    `  <path id="pattern-shapes" d="${combinedHolesD}" fill="${fillAttr}" fill-rule="evenodd" stroke="${strokeAttr}" stroke-width="${fmt(strokeW)}" stroke-linejoin="round" />`,
    `</svg>`,
  ]
    .filter(Boolean)
    .join('\n');
}

/**
 * Generates a Laser Cutting / CNC-ready SVG (LightBurn, Epilog, Trotec compatible).
 * - HOLES layer: no fill, pure red #FF0000, 0.1mm hairline stroke
 * - PANEL_OUTLINE layer: no fill, pure blue #0000FF, 0.1mm hairline stroke
 */
export function buildLaserSvg(state: PatternState, result: PatternResult): string {
  const { panelW, panelH } = state;
  const panelD = ringToPathD(result.panelOutline);

  const holeElements: string[] = [];
  for (const inst of result.instances) {
    const rings = inst.clippedRings
      ? inst.clippedRings
      : result.baseRings.map((r) => transformRing(r, inst.x, inst.y, inst.angle, inst.scale));
    for (const ring of rings) {
      const d = ringToPathD(ring);
      if (d) {
        holeElements.push(`    <path d="${d}" />`);
      }
    }
  }

  return [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<svg xmlns="http://www.w3.org/2000/svg" width="${fmt(panelW)}mm" height="${fmt(panelH)}mm" viewBox="0 0 ${fmt(panelW)} ${fmt(panelH)}">`,
    `  <!-- Laser Cut Ready (1:1 mm) — Pass 1: Red #FF0000 (HOLES) | Pass 2: Blue #0000FF (PANEL_OUTLINE) -->`,
    `  <g id="HOLES" fill="none" stroke="#FF0000" stroke-width="0.1" stroke-linejoin="round">`,
    ...holeElements,
    `  </g>`,
    `  <g id="PANEL_OUTLINE" fill="none" stroke="#0000FF" stroke-width="0.1" stroke-linejoin="round">`,
    `    <path d="${panelD}" />`,
    `  </g>`,
    `</svg>`,
  ].join('\n');
}

export function triggerTextDownload(content: string, fileName: string, mimeType: string): void {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
